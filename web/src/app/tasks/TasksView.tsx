"use client";
import { useRouter } from "next/navigation";
import Link from "next/link";
import { useMemo, useState } from "react";
import { Badge, Chip, EmptyState, ErrorState, LoadingBlock, PageHeader, SearchInput, Table, Td, Th, Tr, cx } from "@/components/ui";
import { useApi, type TasksResponse } from "@/lib/ui/api";
import { taskHref, usd } from "@/lib/ui/format";

const PAGE = 100;

export default function TasksView() {
  const router = useRouter();
  const { data, error, loading, reload } = useApi<TasksResponse>("/api/tasks");
  const [q, setQ] = useState("");
  const [tags, setTags] = useState<string[]>([]);
  const [kind, setKind] = useState<"all" | "base" | "adversarial">("all");
  const [limit, setLimit] = useState(PAGE);

  const all = data?.tasks ?? [];
  const filtered = useMemo(() => {
    const s = q.trim().toLowerCase();
    return all.filter((t) =>
      (kind === "all" || (kind === "adversarial") === t.adversarial) &&
      (!tags.length || tags.every((g) => t.tags.includes(g))) &&
      (!s || t.instruction.toLowerCase().includes(s) || t.id.toLowerCase().includes(s)));
  }, [all, q, tags, kind]);
  const nAdv = all.filter((t) => t.adversarial).length;

  return (
    <>
      <PageHeader tone="gold" title="Tasks"
        description="Shopping instructions with a hard budget. Base tasks are hand-written; adversarial tasks are generated by the red team from scams that fooled a model." />
      {error && <ErrorState error={error} onRetry={reload} />}

      <div className="mb-3 flex flex-wrap items-center gap-2">
        <SearchInput value={q} onChange={setQ} placeholder="Search instructions or ids" className="w-72 max-sm:w-full" />
        <div className="flex gap-0.5 rounded-md bg-canvas-sunk p-0.5 text-[13px]">
          {([["all", `All ${all.length}`], ["base", `Base ${all.length - nAdv}`], ["adversarial", `Adversarial ${nAdv}`]] as const).map(([k, l]) => (
            <button key={k} type="button" onClick={() => setKind(k)}
              className={cx("rounded px-2.5 py-1 tnum max-lg:min-h-10", kind === k ? "bg-white font-medium text-ink shadow-sm" : "text-ink-2 hover:text-ink")}>{l}</button>
          ))}
        </div>
        <span className="ml-auto text-[13px] text-ink-3 tnum">{filtered.length} shown</span>
      </div>
      {data?.tags?.length ? (
        <div className="mb-5 flex flex-wrap gap-1.5">
          {data.tags.map((t) => (
            <Chip key={t.tag} active={tags.includes(t.tag)} count={t.count}
              onClick={() => setTags((s) => (s.includes(t.tag) ? s.filter((x) => x !== t.tag) : [...s, t.tag]))}>{t.tag}</Chip>
          ))}
          {tags.length > 0 && <button onClick={() => setTags([])} className="px-2 text-[12.5px] text-ink-3 hover:text-ink max-lg:min-h-10">Clear</button>}
        </div>
      ) : null}

      {loading && !data ? <LoadingBlock rows={10} /> : filtered.length ? (
        <>
          {/* Phones: one card per task */}
          <ul className="divide-y divide-divider overflow-hidden rounded-lg border border-divider bg-white sm:hidden">
            {filtered.slice(0, limit).map((t) => (
              <li key={t.id}>
                <Link href={taskHref(t.id)} className="block px-4 py-3 transition-colors active:bg-ivory">
                  <div className="flex items-baseline justify-between gap-3">
                    <span className="min-w-0 truncate font-mono text-[12.5px] text-ink-3">{t.id}</span>
                    <span className="shrink-0 font-mono text-[12.5px] text-ink tnum">{usd(t.budget)}</span>
                  </div>
                  <p className="mt-1 line-clamp-2 text-[13.5px] leading-snug text-ink">{t.instruction}</p>
                  <div className="mt-1.5 flex flex-wrap items-center gap-1">
                    {t.adversarial && <Badge tone="warn">Adversarial</Badge>}
                    {t.tags.slice(0, 3).map((g) => <span key={g} className="whitespace-nowrap rounded bg-canvas-sunk px-1.5 py-0.5 text-[11.5px] text-ink-2">{g}</span>)}
                    {t.tags.length > 3 && <span className="text-[11.5px] text-ink-4">+{t.tags.length - 3}</span>}
                  </div>
                </Link>
              </li>
            ))}
          </ul>
          <Table className="max-sm:hidden" stickyFirst>
            <thead>
              <tr>
                <Th>Task</Th>
                <Th>Instruction</Th>
                <Th align="right">Budget</Th>
                <Th>Tags</Th>
              </tr>
            </thead>
            <tbody>
              {filtered.slice(0, limit).map((t) => (
                <Tr key={t.id} onClick={() => router.push(taskHref(t.id))}>
                  <Td className="w-[150px] whitespace-nowrap">
                    <Link href={taskHref(t.id)} onClick={(e) => e.stopPropagation()} className="tap font-mono text-[12.5px] text-ink-2 hover:text-accent">{t.id}</Link>
                  </Td>
                  <Td className="max-w-[520px] max-lg:min-w-[260px] max-lg:max-w-[320px]">
                    <div className="flex items-center gap-2">
                      {t.adversarial && <Badge tone="warn">Adversarial</Badge>}
                      <span className="truncate text-ink" title={t.instruction}>{t.instruction}</span>
                    </div>
                  </Td>
                  <Td align="right" mono className="text-ink">{usd(t.budget)}</Td>
                  <Td className="w-[300px]">
                    <div className="flex gap-1 overflow-hidden">
                      {t.tags.slice(0, 2).map((g) => <span key={g} className="whitespace-nowrap rounded bg-canvas-sunk px-1.5 py-0.5 text-[11.5px] text-ink-2">{g}</span>)}
                      {t.tags.length > 2 && <span className="self-center text-[11.5px] text-ink-4" title={t.tags.slice(2).join(", ")}>+{t.tags.length - 2}</span>}
                    </div>
                  </Td>
                </Tr>
              ))}
            </tbody>
          </Table>
          {filtered.length > limit && (
            <div className="mt-3 text-center">
              <button onClick={() => setLimit((l) => l + PAGE)} className="text-[13px] text-accent hover:underline max-lg:min-h-10">Show {Math.min(PAGE, filtered.length - limit)} more</button>
            </div>
          )}
        </>
      ) : !error && <EmptyState title="No tasks match" description="Try clearing filters." />}
    </>
  );
}

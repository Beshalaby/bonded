"use client";
import { useRef } from "react";
import { ArrowRight } from "lucide-react";
import { Heatmap, ScaleLegend } from "@/components/charts";
import LeaderboardTable from "@/components/LeaderboardTable";
import RunsList from "@/components/RunsList";
import { ButtonLink, EmptyState, ErrorState, LoadingBlock, PageHeader, Section, Skeleton, Stat, StatStrip, TextLink } from "@/components/ui";
import { useEvents } from "@/components/useEvents";
import { useApi, type LeaderboardResponse, type RunsResponse } from "@/lib/ui/api";
import { TRAP_LABEL, TRAP_TYPES, ago, modelHref } from "@/lib/ui/format";

export default function HomeView() {
  const lb = useApi<LeaderboardResponse>("/api/leaderboard");
  const runs = useApi<RunsResponse>("/api/runs");
  const t = useRef<ReturnType<typeof setTimeout> | null>(null);
  useEvents(["result", "run"], () => {
    if (t.current) return;
    t.current = setTimeout(() => { t.current = null; lb.reload(); runs.reload(); }, 1500);
  });

  const rows = lb.data?.rows ?? [];
  const totals = lb.data?.totals;

  return (
    <>
      <PageHeader
        title="How safely do AI agents spend money?"
        description="SpendBench evaluates shopping agents in a sandbox store seeded with scams, prompt injections and budget traps. Every action is traced, every failure is attributed."
        meta={lb.data && <span>Updated {ago(lb.data.updatedAt)} · latest result per model × task</span>}
        actions={<ButtonLink href="/runs/new" variant="secondary">Run the benchmark</ButtonLink>}
      />

      {lb.error && <div className="mb-6"><ErrorState error={lb.error} onRetry={lb.reload} /></div>}

      {totals ? (
        <StatStrip cols={4}>
          <Stat label="Models evaluated" value={<span className="tnum">{totals.models}</span>}
            sub={(() => { const sim = rows.filter((r) => r.simulated).length; return sim === rows.length ? "all simulated agents" : `${rows.length - sim} LLM · ${sim} simulated`; })()} />
          <Stat label="Tasks" value={<span className="tnum">{totals.tasks}</span>} sub={`${totals.trapListings} trap listings in the Arena`} />
          <Stat label="Graded results" value={<span className="tnum">{totals.results.toLocaleString()}</span>} sub={`across ${totals.runs} run${totals.runs === 1 ? "" : "s"}`} />
          <Stat label="Adversarial scams" value={<span className="tnum">{totals.scams}</span>} sub={<TextLink href="/redteam">generated by the red team</TextLink>} />
        </StatStrip>
      ) : !lb.error && <Skeleton className="h-[86px]" />}

      <Section title="Leaderboard" className="!mt-10"
        description="Ranked by composite score. Reliability is the posterior probability of success with a 90% credible interval; click a column to sort.">
        {lb.loading && !lb.data ? <LoadingBlock rows={6} /> : rows.length ? <LeaderboardTable rows={rows} /> : !lb.error && (
          <EmptyState title="No results yet" description="Start a run to evaluate models in the Arena. Results appear here as each task is graded."
            action={<ButtonLink href="/runs/new">New run</ButtonLink>} />
        )}
      </Section>

      {rows.length > 0 && (
        <Section title="Trap resistance"
          description="Share of trap-tagged tasks where the model was fooled, by trap type. Lower is better; k/n is fooled over exposed."
          actions={<ScaleLegend label="Fooled" />}>
          <div className="rounded-lg border border-zinc-200 bg-white p-4">
            <Heatmap
              rows={rows.map((r) => ({ key: r.model, label: r.displayName.replace(/\s*\(sim\)\s*$/i, "") }))}
              cols={TRAP_TYPES.map((k) => ({ key: k, label: TRAP_LABEL[k] }))}
              rowHref={modelHref}
              cell={(m, k) => {
                const b = rows.find((r) => r.model === m)?.byTrap?.[k as keyof typeof TRAP_LABEL];
                return b ? { rate: b.exposed ? b.fooled / b.exposed : null, fooled: b.fooled, exposed: b.exposed, lower: b.rate.lower, upper: b.rate.upper } : undefined;
              }}
            />
          </div>
        </Section>
      )}

      <Section title="Latest runs" actions={<TextLink href="/runs" className="inline-flex items-center gap-1">All runs <ArrowRight size={13} /></TextLink>}>
        {runs.data?.runs.length ? <RunsList runs={runs.data.runs.slice(0, 5)} compact />
          : runs.loading ? <LoadingBlock rows={3} />
          : <EmptyState title="No runs yet" description="Start one to grade models against the task suite." action={<ButtonLink href="/runs/new">New run</ButtonLink>} />}
      </Section>
    </>
  );
}
